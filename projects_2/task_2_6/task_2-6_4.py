# Картина В. М. Васнецова «Витязь на распутье».
# Витязь стоит у камня и выбирает дорогу.
print("Перед тобой камень с надписью. Куда поедешь?")
road = input("налево / направо / прямо: ").strip().lower()

if road == "налево" or road == "лево":
    print("Налево поедешь — себя потеряешь, коня спасёшь.")
elif road == "направо" or road == "право":
    print("Направо поедешь — коня потеряешь, себя спасёшь.")
elif road == "прямо" or road == "вперёд":
    print("Прямо поедешь — и себя, и коня потеряешь.")
else:
    print("Витязь постоял у камня и поехал домой.")
